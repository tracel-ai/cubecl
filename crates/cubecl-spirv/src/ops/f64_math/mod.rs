#[cube]
fn atan2_lanes<F: Float, N: Size>(y: Vector<F, N>, x: Vector<F, N>) -> Vector<F, N> {
    let mut out = Vector::<F, N>::empty();
    #[unroll]
    for i in 0..out.vector_size() {
        let lane = atan2(f64::cast_from(y.extract(i)), f64::cast_from(x.extract(i)));
        out.insert(i, F::cast_from(lane));
    }
    out
}

#[cube]
fn pow_lanes<F: Float, N: Size>(base: Vector<F, N>, exponent: Vector<F, N>) -> Vector<F, N> {
    let mut out = Vector::<F, N>::empty();
    #[unroll]
    for i in 0..out.vector_size() {
        let lane = pow(
            f64::cast_from(base.extract(i)),
            f64::cast_from(exponent.extract(i)),
        );
        out.insert(i, F::cast_from(lane));
    }
    out
}

/// Lowers an f64 op to its lane function, and marks the float arithmetic the function adds so
/// that the driver keeps each rounding step. The double-double steps rely on it.
macro_rules! lower_exact {
    ($ty: ty, $name: ident, $($operand: literal),+) => {
        #[op_interface_impl]
        impl LowerOp for $ty {
            fn should_lower(&self, ctx: &Context) -> bool {
                is_f64(self, ctx)
            }

            fn lower(&self, scope: &Scope) -> Vec<Value> {
                define_scalar!(T);
                define_size!(S);
                let op = self.get_operation();
                let uniformity = op_dyn_uniformity(scope.ctx(), op);
                let previous = op.deref(&scope.ctx()).get_prev();
                scope.register_value_type::<T, S>(op.operand(scope.ctx(), 0));
                let value = $name::expand::<T, S>(scope, $(op.operand(scope.ctx(), $operand).into()),+)
                    .read_value(scope);
                mark_no_contraction(&scope.ctx(), op, previous);
                if let DefiningEntity::Op(result) = value.defining_entity() {
                    decorate_uniform(&scope.ctx(), result, uniformity);
                }
                vec![value]
            }
        }
    };
}

