fn is_f64(op: &impl OneResultInterface, ctx: &Context) -> bool {
    op.get_result(ctx).scalar_ty(ctx).is_float64(ctx)
}

// Each wrapper applies a scalar f64 function to each lane. A GPU thread runs an f64 vector one
// lane at a time, so the scalar form costs nothing, and it lets a rare slow path branch per lane.

#[cube]
fn sin_lanes<F: Float, N: Size>(x: Vector<F, N>) -> Vector<F, N> {
    let mut out = Vector::<F, N>::empty();
    #[unroll]
    for i in 0..out.vector_size() {
        out.insert(i, F::cast_from(sin(f64::cast_from(x.extract(i)))));
    }
    out
}

